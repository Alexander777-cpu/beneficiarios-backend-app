-- =====================================================================
-- V1: Esquema Principal del Sistema de Gestion de Beneficiarios (Oracle)
-- =====================================================================

CREATE TABLE facultades (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT pk_facultades PRIMARY KEY (id),
    CONSTRAINT ux_facultades_nombre UNIQUE (nombre)
);

CREATE TABLE proyectos (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(150 CHAR) NOT NULL,
    facultad_id        NUMBER(19, 0)      NOT NULL,
    CONSTRAINT pk_proyectos PRIMARY KEY (id),
    CONSTRAINT fk_proyectos_facultad FOREIGN KEY (facultad_id)
        REFERENCES facultades (id),
    CONSTRAINT ux_proyectos_nombre_fac UNIQUE (nombre, facultad_id)
);

CREATE INDEX ix_proyectos_facultad ON proyectos (facultad_id);

CREATE TABLE talleres (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT pk_talleres PRIMARY KEY (id),
    CONSTRAINT ux_talleres_nombre UNIQUE (nombre)
);

CREATE TABLE proyecto_talleres (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    proyecto_id        NUMBER(19, 0) NOT NULL,
    taller_id          NUMBER(19, 0) NOT NULL,
    CONSTRAINT pk_proyecto_talleres PRIMARY KEY (id),
    CONSTRAINT fk_pt_proyecto FOREIGN KEY (proyecto_id)
        REFERENCES proyectos (id),
    CONSTRAINT fk_pt_taller FOREIGN KEY (taller_id)
        REFERENCES talleres (id),
    CONSTRAINT ux_pt_proyecto_taller UNIQUE (proyecto_id, taller_id)
);

CREATE INDEX ix_pt_proyecto ON proyecto_talleres (proyecto_id);
CREATE INDEX ix_pt_taller ON proyecto_talleres (taller_id);

CREATE TABLE beneficiarios (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    tipo_beneficiario  VARCHAR2(50 CHAR)  NOT NULL,
    nombres            VARCHAR2(100 CHAR) NOT NULL,
    apellido_paterno   VARCHAR2(100 CHAR) NOT NULL,
    apellido_materno   VARCHAR2(100 CHAR) NOT NULL,
    telefono           VARCHAR2(15 CHAR),
    edad               NUMBER(3, 0),
    grado_estudios     VARCHAR2(100 CHAR),
    estado_civil       VARCHAR2(50 CHAR),
    tutor_nombre       VARCHAR2(150 CHAR),
    talla_polo         VARCHAR2(10 CHAR),
    talla_pantalon     VARCHAR2(10 CHAR),
    talla_calzado      NUMBER(2, 0),
    proyecto_taller_id NUMBER(19, 0)      NOT NULL,
    fecha_registro     TIMESTAMP(6)       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_beneficiarios PRIMARY KEY (id),
    CONSTRAINT ux_beneficiarios_nombres UNIQUE (nombres),
    CONSTRAINT fk_beneficiarios_pt FOREIGN KEY (proyecto_taller_id)
        REFERENCES proyecto_talleres (id),
    CONSTRAINT ck_beneficiarios_tipo CHECK (tipo_beneficiario IN ('NINO', 'ADOLESCENTE', 'ADULTO'))
);

CREATE INDEX ix_beneficiarios_pt ON beneficiarios (proyecto_taller_id);

CREATE TABLE asistencias (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    fecha              VARCHAR2(10 CHAR) NOT NULL,
    asistio            NUMBER(1, 0)      DEFAULT 0 NOT NULL,
    beneficiario_id    NUMBER(19, 0)     NOT NULL,
    proyecto_taller_id NUMBER(19, 0)     NOT NULL,
    fecha_registro     TIMESTAMP(6)      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_asistencias PRIMARY KEY (id),
    CONSTRAINT fk_asistencias_ben FOREIGN KEY (beneficiario_id)
        REFERENCES beneficiarios (id),
    CONSTRAINT fk_asistencias_pt FOREIGN KEY (proyecto_taller_id)
        REFERENCES proyecto_talleres (id),
    CONSTRAINT ux_asistencia_unica_dia UNIQUE (beneficiario_id, proyecto_taller_id, fecha),
    CONSTRAINT ck_asistencias_asistio CHECK (asistio IN (0, 1))
);

CREATE INDEX ix_asistencias_lookup ON asistencias (proyecto_taller_id, beneficiario_id, fecha);

CREATE TABLE auditorias (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    usuario_accion     VARCHAR2(50 CHAR)   NOT NULL,
    accion             VARCHAR2(50 CHAR)   NOT NULL,
    modulo             VARCHAR2(50 CHAR)   NOT NULL,
    descripcion        VARCHAR2(1000 CHAR) NOT NULL,
    fecha              TIMESTAMP(6)        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_auditorias PRIMARY KEY (id)
);

CREATE INDEX ix_auditorias_fecha ON auditorias (fecha);
